#!/usr/bin/env python3
"""Builds resources/rime/english/scowl.dict.yaml from a SCOWL release.

Usage: Scripts/generate-english-dict.py <scowl-2020.12.07/final> <output>

Takes the english-words and american-words lists at SCOWL levels 10, 20, 35 and 40
(the common words), keeps plain ASCII-letter words of two letters or more, and
weights them by level so the most common words complete first. When a word
appears both in lower case and capitalised (may / May), only the lower-case form
is kept. The output is deterministic for a given SCOWL release.
"""
import pathlib
import re
import sys

LEVELS = {10: 400, 20: 300, 35: 200, 40: 100}


def main() -> None:
    final = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])
    weights: dict[str, int] = {}
    for level, weight in LEVELS.items():
        for kind in ("english", "american"):
            path = final / f"{kind}-words.{level}"
            for raw in path.read_text(encoding="latin-1").splitlines():
                word = raw.strip()
                if len(word) < 2 or not re.fullmatch(r"[A-Za-z]+", word):
                    continue
                weights.setdefault(word, weight)
    lower = {word for word in weights if word.islower()}
    entries = sorted(
        (word for word in weights if word.islower() or word.lower() not in lower),
        key=lambda word: (-weights[word], word.lower(), word),
    )
    lines = [
        "# Rime dictionary",
        "# encoding: utf-8",
        "#",
        "# Generated by IME/Scripts/generate-english-dict.py from SCOWL 2020.12.07",
        "# (english-words and american-words, levels 10/20/35/40). Copyright 2000-2018",
        "# by Kevin Atkinson and others; see LICENSE.scowl in this directory.",
        "",
        "---",
        "name: scowl",
        'version: "2020.12.07"',
        "sort: by_weight",
        "...",
    ]
    lines += [f"{word}\t{word.lower()}\t{weights[word]}" for word in entries]
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"entries={len(entries)}")


if __name__ == "__main__":
    main()
